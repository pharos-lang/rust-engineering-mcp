use m1_16_r04::pages_needed;

#[test]
fn exact_ceiling_for_full_u32_boundary_cases() {
    let cases = [
        (0, 0, None),
        (0, 1, Some(0)),
        (0, 2, Some(0)),
        (0, 3, Some(0)),
        (0, 16, Some(0)),
        (0, 2147483647, Some(0)),
        (0, 4294967294, Some(0)),
        (0, 4294967295, Some(0)),
        (1, 0, None),
        (1, 1, Some(1)),
        (1, 2, Some(1)),
        (1, 3, Some(1)),
        (1, 16, Some(1)),
        (1, 2147483647, Some(1)),
        (1, 4294967294, Some(1)),
        (1, 4294967295, Some(1)),
        (2, 0, None),
        (2, 1, Some(2)),
        (2, 2, Some(1)),
        (2, 3, Some(1)),
        (2, 16, Some(1)),
        (2, 2147483647, Some(1)),
        (2, 4294967294, Some(1)),
        (2, 4294967295, Some(1)),
        (15, 0, None),
        (15, 1, Some(15)),
        (15, 2, Some(8)),
        (15, 3, Some(5)),
        (15, 16, Some(1)),
        (15, 2147483647, Some(1)),
        (15, 4294967294, Some(1)),
        (15, 4294967295, Some(1)),
        (16, 0, None),
        (16, 1, Some(16)),
        (16, 2, Some(8)),
        (16, 3, Some(6)),
        (16, 16, Some(1)),
        (16, 2147483647, Some(1)),
        (16, 4294967294, Some(1)),
        (16, 4294967295, Some(1)),
        (17, 0, None),
        (17, 1, Some(17)),
        (17, 2, Some(9)),
        (17, 3, Some(6)),
        (17, 16, Some(2)),
        (17, 2147483647, Some(1)),
        (17, 4294967294, Some(1)),
        (17, 4294967295, Some(1)),
        (2147483647, 0, None),
        (2147483647, 1, Some(2147483647)),
        (2147483647, 2, Some(1073741824)),
        (2147483647, 3, Some(715827883)),
        (2147483647, 16, Some(134217728)),
        (2147483647, 2147483647, Some(1)),
        (2147483647, 4294967294, Some(1)),
        (2147483647, 4294967295, Some(1)),
        (4294967294, 0, None),
        (4294967294, 1, Some(4294967294)),
        (4294967294, 2, Some(2147483647)),
        (4294967294, 3, Some(1431655765)),
        (4294967294, 16, Some(268435456)),
        (4294967294, 2147483647, Some(2)),
        (4294967294, 4294967294, Some(1)),
        (4294967294, 4294967295, Some(1)),
        (4294967295, 0, None),
        (4294967295, 1, Some(4294967295)),
        (4294967295, 2, Some(2147483648)),
        (4294967295, 3, Some(1431655765)),
        (4294967295, 16, Some(268435456)),
        (4294967295, 2147483647, Some(3)),
        (4294967295, 4294967294, Some(2)),
        (4294967295, 4294967295, Some(1)),
    ];
    for (items, size, expected) in cases {
        assert_eq!(
            pages_needed(items, size),
            expected,
            "items={items}, size={size}"
        );
    }
}
