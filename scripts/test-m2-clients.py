def walk_json(value: object):
    yield value
    if isinstance(value, dict):
        for child in value.values():
            yield from walk_json(child)
    elif isinstance(value, list):
        for child in value:
            yield from walk_json(child)


def normalize_tool(name: str) -> str | None:
    if not name.startswith("mcp__rust_engineering__"):
        return None
    suffix = name.removeprefix("mcp__rust_engineering__")
    for expected in ("rust.project.open", *M2_TOOLS):
        if suffix in (expected, expected.replace(".", "_")):
            return expected
    return f"unexpected:{suffix}"


def validate_claude_stream(raw: bytes) -> dict:
    calls = []
    by_id = {}
    results = {}
    models = set()
    events = []
    for line in raw.splitlines():
        if not line.strip():
            continue
        event = json.loads(line)
        events.append(event)
        for value in walk_json(event):
            if not isinstance(value, dict):
                continue
            model = value.get("model")
            if isinstance(model, str) and "claude" in model:
                models.add(model)
            if value.get("type") == "tool_use" and isinstance(value.get("name"), str):
                normalized = normalize_tool(value["name"])
                if normalized is None or normalized.startswith("unexpected:"):
                    raise RuntimeError(f"claude_forbidden_tool_{value['name']}")
                identifier = value.get("id")
                if not isinstance(identifier, str) or identifier in by_id:
                    raise RuntimeError("claude_duplicate_or_missing_tool_use_id")
                call = {"id": identifier, "tool": normalized, "input": value.get("input")}
                calls.append(call)
                by_id[identifier] = call
            if value.get("type") == "tool_result":
                identifier = value.get("tool_use_id")
                if not isinstance(identifier, str) or identifier in results:
                    raise RuntimeError("claude_duplicate_or_missing_tool_result_id")
                results[identifier] = value
    if not events or events[-1].get("type") != "result" or events[-1].get("subtype") != "success" or events[-1].get("is_error") is True:
        raise RuntimeError("claude_missing_success_final_event")
    names = [call["tool"] for call in calls]
    if not models or any(not model.startswith(MODEL) for model in models):
        raise RuntimeError("claude_model_identity_or_fallback")
    for tool in M2_TOOLS:
        modes = [call.get("input", {}).get("action", {}).get("mode") for call in calls if call["tool"] == tool]
        if "preview" not in modes or "commit" not in modes:
            raise RuntimeError(f"claude_missing_preview_commit_{tool}")
    fix_modes = [call.get("input", {}).get("action", {}).get("mode") for call in calls if call["tool"] == "rust.fix.apply"]
    if "receipt" not in fix_modes or names.count("rust.project.open") < 6:
        raise RuntimeError("claude_missing_reopen_or_receipt")
    if set(results) != set(by_id):
        raise RuntimeError("claude_unmatched_tool_results")
    observations = []
    for identifier, call in by_id.items():
        result = results[identifier]
        if result.get("is_error") is True:
            raise RuntimeError(f"claude_failed_tool_result_{call['tool']}")
        candidates = []
        for value in walk_json(result.get("content")):
            if isinstance(value, dict) and isinstance(value.get("structuredContent"), dict):
                candidates.append(value["structuredContent"])
            elif isinstance(value, str):
                try:
                    parsed = json.loads(value)
                except json.JSONDecodeError:
                    continue
                for parsed_value in walk_json(parsed):
                    if isinstance(parsed_value, dict) and "status" in parsed_value:
                        candidates.append(parsed_value)
        outputs = [value for value in candidates if value.get("status") in {"passed", "failed", "blocked", "cancelled", "unavailable"}]
        if len(outputs) != 1 or outputs[0].get("status") != "passed":
            raise RuntimeError(f"claude_nonpassing_or_ambiguous_tool_result_{call['tool']}")
        action = call.get("input", {}).get("action", {})
        mode = action.get("mode") if isinstance(action, dict) else None
        if mode == "commit" and outputs[0].get("data", {}).get("state") != "committed":
            raise RuntimeError(f"claude_commit_not_committed_{call['tool']}")
        if mode == "receipt" and outputs[0].get("data", {}).get("state") != "committed":
            raise RuntimeError(f"claude_receipt_not_committed_{call['tool']}")
        observations.append({"tool_use_id": identifier, "tool": call["tool"], "mode": mode, "status": "passed"})
    return {"calls": calls, "results": observations, "tool_call_count": len(calls), "tool_result_count": len(results), "observed_models": sorted(models), "final_event_subtype": "success"}


def run_claude(run: Path, paths: dict[str, Path], socket: str, deadline: float) -> dict:
    config = run / "claude-mcp.json"
    save_json(config, claude_config(paths, socket))
    allowed = [
        "mcp__rust_engineering__rust.project.open",
        *[f"mcp__rust_engineering__{name}" for name in M2_TOOLS],
        "mcp__rust_engineering__rust_project_open",
        *[f"mcp__rust_engineering__{name.replace('.', '_')}" for name in M2_TOOLS],
    ]
    argv = [
        str(CLAUDE), "--print", "--output-format", "stream-json", "--verbose",
        "--model", MODEL, "--effort", EFFORT, "--no-session-persistence",
        "--restricted", "--setting-sources", "", "--strict-mcp-config",
        "--mcp-config", str(config), "--disable-slash-commands", "--no-chrome",
        "--tools", "", "--allowedTools", ",".join(allowed),
        "--permission-mode", "dontAsk", "--permission-prompts", "none",
        "--system-prompt", "You are a bounded third-party MCP client qualifier. Use only the explicitly configured Rust Engineering MCP server and follow the requested preview-review-commit workflow.",
        claude_prompt(paths["project"]),
    ]
    remaining = int(deadline - time.monotonic())
    if remaining < 1:
        raise RuntimeError("qualification_wall_timeout")
    code, stdout, stderr, duration = run_bounded(
        argv, run, safe_environment(paths["home"]), remaining,
        ARTIFACTS / "claude-model-session.json",
    )
    if code != 0:
        raise RuntimeError(f"claude_exit_{code}:stderr_sha256={sha_bytes(stderr)}")
    stream = validate_claude_stream(stdout)
    actual_tree = snapshot(paths["project"])
    expected_bytes = {"Cargo.toml": FINAL_MANIFEST, "Cargo.lock": LOCK, "src/lib.rs": FINAL_SOURCE}
    expected_tree = {name: sha_bytes(value) for name, value in expected_bytes.items()}
    if actual_tree != expected_tree:
        raise RuntimeError("claude_final_source_mismatch")
    return {
        "version": subprocess.run([str(CLAUDE), "--version"], capture_output=True, text=True, timeout=10, check=True).stdout.strip(),
        "executable_sha256": sha_file(CLAUDE),
        "model_requested": MODEL,
        "effort_requested": EFFORT,
        "fallback_configured": False,
        "builtins": [],
        "allowed_mcp_tools": ["rust.project.open", *M2_TOOLS],
        "duration_seconds": round(duration, 3),
        "stderr_sha256": sha_bytes(stderr),
        "stream": stream,
        "final_tree_sha256": actual_tree,
    }


def docker_inventory(run: Path, socket: str) -> dict[str, list[str]]:
    config = run / "docker-config"
    config.mkdir(exist_ok=True, mode=0o700)
    (config / "config.json").write_text("{}\n")
    inventory = {}
    for kind in ("container", "volume"):
        argv = [str(DOCKER), "--config", str(config), "--host", f"unix://{socket}", kind, "ls"]
        if kind == "container":
            argv += ["--all", "--no-trunc"]
        argv += ["--filter", "label=org.rust-mcp.execution=true", "--format", "{{.Names}}" if kind == "container" else "{{.Name}}"]
        result = subprocess.run(argv, env={}, capture_output=True, text=True, timeout=15, check=True)
        inventory[kind + "s"] = [line for line in result.stdout.splitlines() if line]
    return inventory


def prerequisites() -> dict:
    required = (NODE, INSPECTOR, INSPECTOR_PACKAGE, CLAUDE, SERVER, DOCKER)
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise RuntimeError("missing_prerequisites:" + ",".join(missing))
    version = json.loads(INSPECTOR_PACKAGE.read_text())["version"]
    if version != "2.5.0":
        raise RuntimeError(f"inspector_version_{version}")
    claude_version = subprocess.run([str(CLAUDE), "--version"], capture_output=True, text=True, timeout=10, check=True).stdout.strip()
    if not claude_version.startswith("2.1.260"):
        raise RuntimeError(f"claude_version_{claude_version}")
    (WORK / "tmp").mkdir(parents=True, exist_ok=True, mode=0o700)
    auth = subprocess.run(
        [str(CLAUDE), "auth", "status"],
        env=safe_environment(WORK),
        capture_output=True,
        timeout=10,
    )
    try:
        auth_status = json.loads(auth.stdout)
    except (json.JSONDecodeError, UnicodeDecodeError) as error:
        raise RuntimeError("claude_auth_status_invalid") from error
    if auth.returncode != 0 or auth_status.get("loggedIn") is not True:
        raise RuntimeError("claude_normal_api_auth_unavailable")
    return {
        "inspector_version": version,
        "inspector_cli_sha256": sha_file(INSPECTOR),
        "node_sha256": sha_file(NODE),
        "claude_version": claude_version,
        "claude_sha256": sha_file(CLAUDE),
        "claude_auth_method": auth_status.get("authMethod"),
        "server_sha256": sha_file(SERVER),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", action="store_true", help="execute the serialized Docker/model gate")
    parser.add_argument("--docker-socket", default=os.environ.get("RUST_MCP_TEST_SOCKET"))
    options = parser.parse_args()
    identities = prerequisites()
    prepared = {
        "schema": "rust-mcp-m2-third-party-clients-v2",
        "status": "prepared" if not options.run else "running",
        "scope": "Inspector one-shot discovery/default-deny plus one stock Claude model-directed five-tool mutation workflow",
        "limits": {"wall_seconds": WALL_SECONDS, "combined_output_bytes": MAX_OUTPUT},
        "identities": identities,
        "inspector_exit_5_disposition": {
            "installed_source": "target/m1-17-inspector/node_modules/@modelcontextprotocol/inspector/clients/cli/build/index.js",
            "installed_source_sha256": identities["inspector_cli_sha256"],
            "exit_code_definition_lines": "13255-13262",
            "is_error_mapping_lines": "13741-13746",
            "semantics": "Inspector 2.5.0 emits the JSON result, then exits 5 when result.isError is true; only the five expected default-deny calls accept that exit and still require isError:true plus blocked/permission_denied.",
        },
        "expected_tools": list(EXPECTED_TOOLS),
        "expected_model_calls": {
            "rust.project.open": "at least six",
            **{tool: ["preview", "commit"] for tool in M2_TOOLS},
            "rust.fix.apply_receipt": True,
        },
        "security": {
            "claude_restricted": True,
            "builtin_tools": [],
            "strict_mcp_config": True,
            "permission_bypass": False,
            "fallback_model": False,
            "network_claim": "No client network-isolation claim; the normal model API is required. Guest execution remains Docker network=none.",
        },
    }
    save_json(RECEIPT, prepared)
    if not options.run:
        print(RECEIPT)
        return 0
    if not options.docker_socket or not options.docker_socket.startswith("/"):
        raise RuntimeError("explicit_absolute_docker_socket_required")
    run = WORK / f"run-{time.time_ns()}"
    run.mkdir(parents=True, mode=0o700)
    paths = create_fixture(run)
    prepared["run_directory"] = str(run.relative_to(ROOT))
    prepared["fixture_before"] = snapshot(paths["project"])
    prepared["vendor_fingerprint"] = VENDOR_FP
    prepared["docker_before"] = docker_inventory(run, options.docker_socket)
    if any(prepared["docker_before"].values()):
        raise RuntimeError("docker_not_exclusive")
    try:
        deadline = time.monotonic() + WALL_SECONDS
        prepared["inspector"] = inspect_stock_client(run, paths, options.docker_socket, deadline)
        prepared["claude"] = run_claude(run, paths, options.docker_socket, deadline)
        prepared["fixture_after"] = snapshot(paths["project"])
        prepared["docker_after"] = docker_inventory(run, options.docker_socket)
        if any(prepared["docker_after"].values()):
            raise RuntimeError("docker_cleanup_incomplete")
        prepared["status"] = "passed"
        return 0
    except BaseException as error:
        prepared["status"] = "failed"
        prepared["error"] = f"{type(error).__name__}:{error}"
        try:
            prepared["docker_after_failure"] = docker_inventory(run, options.docker_socket)
        except BaseException as inventory_error:
            prepared["docker_inventory_error"] = str(inventory_error)
        raise
    finally:
        save_json(RECEIPT, prepared)
        print(RECEIPT, flush=True)


if __name__ == "__main__":
    raise SystemExit(main())
