def run_bounded(
    argv: list[str], cwd: Path, environment: dict[str, str], timeout: int, artifact: Path
) -> tuple[int, bytes, bytes, float]:
    started = time.monotonic()
    child = subprocess.Popen(
        argv,
        cwd=cwd,
        env=environment,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        start_new_session=True,
    )
    selector = selectors.DefaultSelector()
    buffers = {"stdout": bytearray(), "stderr": bytearray()}
    total = 0
    failure = None
    failed_at = None
    deadline = started + timeout
    for name, pipe in (("stdout", child.stdout), ("stderr", child.stderr)):
        os.set_blocking(pipe.fileno(), False)
        selector.register(pipe, selectors.EVENT_READ, name)
    while child.poll() is None or selector.get_map():
        now = time.monotonic()
        if failure is None and now >= deadline:
            failure = "command_timeout"
            failed_at = now
            try:
                os.killpg(child.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        for key, _ in selector.select(0.05):
            try:
                block = os.read(key.fileobj.fileno(), 65536)
            except BlockingIOError:
                continue
            if not block:
                selector.unregister(key.fileobj)
                key.fileobj.close()
                continue
            total += len(block)
            remaining = max(0, MAX_OUTPUT - sum(len(value) for value in buffers.values()))
            buffers[key.data].extend(block[:remaining])
            if failure is None and total > MAX_OUTPUT:
                failure = "command_output_limit"
                failed_at = time.monotonic()
                try:
                    os.killpg(child.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
        if failure is not None and child.poll() is not None and not selector.get_map():
            break
        if failed_at is not None and time.monotonic() - failed_at >= 10:
            for registered in list(selector.get_map().values()):
                selector.unregister(registered.fileobj)
                registered.fileobj.close()
            break
    selector.close()
    child.wait()
    stdout, stderr = bytes(buffers["stdout"]), bytes(buffers["stderr"])
    duration = time.monotonic() - started
    artifact.parent.mkdir(parents=True, exist_ok=True)
    artifact.with_suffix(".stdout").write_bytes(stdout)
    artifact.with_suffix(".stderr").write_bytes(stderr)
    save_json(
        artifact,
        {
            "argv": argv,
            "exit_code": child.returncode,
            "duration_seconds": round(duration, 3),
            "stdout_bytes": len(stdout),
            "stdout_sha256": sha_bytes(stdout),
            "stderr_bytes": len(stderr),
            "stderr_sha256": sha_bytes(stderr),
            "status": "failed" if failure else "complete",
            "failure": failure,
            "observed_output_bytes": total,
        },
    )
    if failure is not None:
        raise RuntimeError(failure)
    return child.returncode, stdout, stderr, duration


def copy_vendor(destination: Path) -> None:
    source = ROOT / "fixtures/cargo-vendor-data/vendor"
    shutil.copytree(source, destination, symlinks=False)
    for item in destination.rglob("*"):
        if item.is_symlink() or not (item.is_dir() or item.is_file()):
            raise RuntimeError("vendor_special_entry")


def create_fixture(run: Path) -> dict[str, Path]:
    project = run / "project"
    state = run / "state"
    home = run / "home"
    for directory in (project / "src", state, home / "tmp"):
        directory.mkdir(parents=True, mode=0o700)
    (project / "Cargo.toml").write_bytes(INITIAL_MANIFEST)
    (project / "Cargo.lock").write_bytes(LOCK)
    (project / "src/lib.rs").write_bytes(INITIAL_SOURCE)
    vendor = run / "vendor"
    copy_vendor(vendor)
    return {"project": project, "state": state, "home": home, "vendor": vendor}


def snapshot(root: Path) -> dict[str, str]:
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise RuntimeError("fixture_symlink")
        if path.is_file():
            result[str(path.relative_to(root))] = sha_file(path)
    return result


def server_args(paths: dict[str, Path], socket: str, grants: bool) -> list[str]:
    arguments = [
        "serve", "--stdio", "--root", str(paths["project"]),
        "--docker", str(DOCKER), "--docker-socket", socket,
        "--state-root", str(paths["state"]), "--rust-image", IMAGE,
    ]
    if grants:
        for flag in (
            "--allow-manifest-write", "--allow-fmt-write", "--allow-fix-write",
            "--allow-dependency-add", "--allow-dependency-remove",
        ):
            arguments += [flag, str(paths["project"])]
        arguments += [
            "--cargo-vendor-dir", str(paths["vendor"]),
            "--cargo-vendor-tree-sha256", VENDOR_FP,
        ]
    return arguments


def inspector_call(
    run: Path,
    environment: dict[str, str],
    label: str,
    args: list[str],
    method: str,
    tool: str | None = None,
    tool_args: dict | None = None,
    deadline: float | None = None,
    expected_tool_error: bool = False,
) -> dict:
    argv = [str(NODE), str(INSPECTOR), str(SERVER), *args, "--", "--method", method,
            "--format", "json", "--stored-auth-only"]
    if method == "tools/list":
        argv.append("--strict")
    if tool is not None:
        argv += ["--tool-name", tool, "--tool-args-json", json.dumps(tool_args, separators=(",", ":"))]
    remaining = 180 if deadline is None else min(180, int(deadline - time.monotonic()))
    if remaining < 1:
        raise RuntimeError("qualification_wall_timeout")
    code, stdout, _, _ = run_bounded(argv, run, environment, remaining, ARTIFACTS / f"inspector-{label}.json")
    expected_code = 5 if expected_tool_error else 0
    if code != expected_code:
        raise RuntimeError(f"inspector_{label}_exit_{code}")
    response = json.loads(stdout)
    if expected_tool_error:
        result = response.get("result", response)
        if not isinstance(result, dict) or result.get("isError") is not True:
            raise RuntimeError(f"inspector_{label}_missing_tool_error")
    return response


def structured(result: dict) -> dict:
    value = result.get("result", result)
    content = value.get("structuredContent") if isinstance(value, dict) else None
    if not isinstance(content, dict):
        raise RuntimeError("missing_structured_content")
    return content


def inspect_stock_client(run: Path, paths: dict[str, Path], socket: str, deadline: float) -> dict:
    environment = safe_environment(paths["home"])
    denied_args = server_args(paths, socket, False)
    discovery = inspector_call(run, environment, "discovery", denied_args, "tools/list", deadline=deadline)
    tools = discovery.get("result", discovery).get("tools")
    if not isinstance(tools, list) or [tool.get("name") for tool in tools] != list(EXPECTED_TOOLS):
        raise RuntimeError("inspector_tool_inventory")
    by_name = {tool["name"]: tool for tool in tools}
    snapshot_dir = ROOT / "crates/mcp-server/tests/snapshots"
    unchanged = {}
    for name, filename in M1_SNAPSHOTS.items():
        expected = json.loads((snapshot_dir / filename).read_text())
        if by_name[name] != expected:
            raise RuntimeError(f"m1_snapshot_changed_{name}")
        unchanged[name] = sha_bytes(canonical(expected))
    opened = inspector_call(
        run, environment, "open", denied_args, "tools/call", "rust.project.open",
        {"path": str(paths["project"])}, deadline=deadline,
    )
    if structured(opened).get("status") != "passed":
        raise RuntimeError("inspector_open_failed")
    fake_ref = "prj_" + "0" * 32
    fake_fp = "sha256:" + "0" * 64
    calls = {
        "rust.manifest.patch": {"project_ref": fake_ref, "action": {"mode": "preview", "expected_project_fingerprint": fake_fp, "edit": {"operation": "lint_set", "scope": "package", "tool": "rust", "name": "unsafe_code", "level": "forbid", "priority": 0}}},
        "rust.fmt.apply": {"project_ref": fake_ref, "action": {"mode": "preview", "expected_project_fingerprint": fake_fp}},
        "rust.fix.apply": {"project_ref": fake_ref, "action": {"mode": "preview", "expected_project_fingerprint": fake_fp}},
        "rust.dependency.add": {"project_ref": fake_ref, "action": {"mode": "preview", "expected_project_fingerprint": fake_fp, "name": "quote", "requirement": "=1.0.47"}},
        "rust.dependency.remove": {"project_ref": fake_ref, "action": {"mode": "preview", "expected_project_fingerprint": fake_fp, "name": "quote"}},
    }
    denied = {}
    for index, (name, arguments) in enumerate(calls.items(), 1):
        response = inspector_call(
            run, environment, f"deny-{index}", denied_args, "tools/call", name,
            arguments, deadline, expected_tool_error=True,
        )
        output = structured(response)
        if output.get("status") != "blocked" or output.get("error_code") != "permission_denied":
            raise RuntimeError(f"inspector_default_deny_{name}")
        denied[name] = output["error_code"]
    return {
        "version": json.loads(INSPECTOR_PACKAGE.read_text())["version"],
        "cli_sha256": sha_file(INSPECTOR),
        "node_sha256": sha_file(NODE),
        "tool_count": len(tools),
        "tool_names": list(EXPECTED_TOOLS),
        "canonical_inventory_sha256": sha_bytes(canonical(tools)),
        "m1_snapshots": unchanged,
        "positive_open": True,
        "default_denials": denied,
        "limitation": "Inspector CLI is one-shot; project references cannot be carried into a later invocation.",
    }


